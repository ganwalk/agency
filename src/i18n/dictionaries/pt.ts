// typeof pt sozinho travaria os outros idiomas nos literais exatos do
// português (com `as const`, cada string vira o próprio tipo literal).
// DeepStringify mantém o formato do dicionário, mas relaxa toda folha de
// texto para `string`, então TypeScript ainda aponta chave faltando ou
// campo errado, só não exige o mesmo texto.
type DeepStringify<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly DeepStringify<U>[]
    : T extends object
      ? { [K in keyof T]: DeepStringify<T[K]> }
      : T;

export type Dictionary = DeepStringify<typeof pt>;
